export function displayError(code: string, language: Language, fallback?: string): string {
  const entry = (errorCopy as Record<string, Record<Language, string>>)[code];
  return entry?.[language] ?? fallback ?? code;
}

/** 置信度（0~1 概率）展示 */
const confidenceCopy: Record<Language, { label: string }> = {
  zh: { label: '置信度' },
  en: { label: 'Confidence' },
};
export function confidenceLabel(value: number, language: Language): string {
  return `${confidenceCopy[language].label} ${Math.round(value * 100)}%`;
}

